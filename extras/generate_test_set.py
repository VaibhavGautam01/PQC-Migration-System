"""
generate_test_set.py - Week 5 Day 1 (Analyzer): build a LABELLED test set from our own
projects, for the Stego Analyzer's detector and cipher-identifier (Week 6, SA1/SA2/SA6).

WHAT IT GENERATES
------------------
Every combination of:
  HIDING METHOD   lsb        plain LSB replacement, 1 bit per pixel byte, keyless
                  xor_lsb    LSB replacement XORed with a keystream derived from a secret key
                             (keyed; this script's OWN definition - see the note below)
                  clean      no hiding at all (a negative example for the detector)
  CIPHER          rsa_textbook   no padding, toy N from --toy-n (default 15, 21, 35, plus one
                                 larger "too big for the Shor stage" case at 512 bits)
                  rsa_oaep       real PKCS#1 OAEP padding, a real pycryptodome RSA key
                                 (--oaep-bits, default 1024)
                  mlkem_hybrid   ML-KEM-768 + AES-256-GCM via pqc_stego.hybrid (reused, not
                                 reimplemented)
                  none           only for the "clean" method (no cipher at all)

For every stego image written, a matching ground-truth record goes into manifest.json:
filename, true method, true cipher, the modulus/key size where relevant, and anything a
later verification step needs (e.g. the toy RSA's p, q, e, d so Q2's Shor stage can be
checked against a KNOWN answer, same pattern as Q1/Q10's self-tests).

A NOTE ON "XOR-LSB"
---------------------
This project's pinned image project may implement XOR-LSB differently; this script does not
know that exact algorithm and does not try to reproduce it bit-for-bit. What matters for a
test SET is that the method is well-defined, documented, and consistently labelled - the
detector (Week 6 SA1) is trained/measured against whatever this script actually does, with
the ground truth it writes. This script's XOR-LSB: bit i of the payload is embedded as
LSB(pixel_byte_i) = plain_LSB_bit XOR keystream_bit_i, where the keystream is
SHA-256(key || counter) bytes, unpacked to bits. Recovering the message needs the key; this
makes it a KEYED hiding method (contrast with lsb, which is keyless), matching this project's
own risk-model distinction (F6: "keyless = 100" vs "keyed ... = 30/90").

HONEST LIMITS
-------------
* Toy RSA (no padding) uses small HAND-PICKED primes, not a library RSA key - that is what
  makes it toy-size and Shor-attackable at all (see src/q1_shor_pe.py's qubit limits).
* OAEP and the ML-KEM hybrid use REAL keys at realistic sizes, so cipher_identify.py (Week 6)
  has something genuine to recognise by structure (byte lengths, KEM ciphertext prefix),
  not by a toy shortcut.
* Per the working rules, these images are GENERATED BY SCRIPT and must never be committed to
  git - the manifest and images belong under outputs/, which .gitignore should already cover
  for generated content (check before committing anything from a run of this script).

Usage (from the project root, venv active):
  python extras/generate_test_set.py
  python extras/generate_test_set.py --out-dir outputs/test_set --count 2 --seed 7
  python extras/generate_test_set.py --toy-n 15 21 35 221 --oaep-bits 1024
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from pqc_stego import hybrid                                 # noqa: E402  (ML-KEM + AES-GCM, reused)

HEADER_BITS = 32                      # same reference wire format as src/quantum_break_stego.py
TOY_KEY_TABLE = {                     # hand-picked small primes: e, d precomputed for self-tests
    15: {"p": 3, "q": 5, "e": 3},
    21: {"p": 3, "q": 7, "e": 5},
    35: {"p": 5, "q": 7, "e": 5},
    221: {"p": 13, "q": 17, "e": 7},  # the stretch-goal size from Q2/Q10's plan
}
LARGE_TOY_BITS = 512                  # "too big for the Shor stage here" case, for the estimate branch


# ------------------------------------------------------------------ hiding methods
def make_cover(size: int, seed: int) -> np.ndarray:
    """A synthetic RGB cover image. Real project covers can be substituted by editing this
    function; what matters for the test set is that every (method, cipher) pair uses an
    independently seeded cover so images are not trivially distinguishable by content alone.
    """
    rng = np.random.default_rng(seed)
    return rng.integers(0, 256, (size, size, 3), dtype=np.uint8)


def embed_lsb(cover: np.ndarray, payload: bytes) -> np.ndarray:
    """Plain LSB replacement, 1 bit per pixel byte, keyless. 32-bit length header first."""
    flat = cover.reshape(-1).copy()
    data = struct.pack(">I", len(payload)) + payload
    bits = np.unpackbits(np.frombuffer(data, dtype=np.uint8))
    if bits.size > flat.size:
        raise ValueError(f"payload ({len(payload)} B) does not fit in this cover "
                         f"(capacity {flat.size // 8 - 4} B)")
    flat[:bits.size] = (flat[:bits.size] & 0xFE) | bits
    return flat.reshape(cover.shape)


def extract_lsb(stego: np.ndarray) -> bytes:
    flat = stego.reshape(-1)
    (length,) = struct.unpack(">I", np.packbits(flat[:HEADER_BITS] & 1).tobytes())
    end = HEADER_BITS + length * 8
    if end > flat.size:                                        # garbage/wrong-key header guard
        raise ValueError(f"decoded length ({length} B) exceeds this image's capacity "
                         f"({flat.size // 8} B) - wrong key, wrong method, or not a stego image")
    return np.packbits(flat[HEADER_BITS:end] & 1).tobytes()


def _keystream_bits(key: bytes, nbits: int) -> np.ndarray:
    """SHA-256(key || counter) bytes, unpacked to bits, as many blocks as needed."""
    out = bytearray()
    counter = 0
    while len(out) * 8 < nbits:
        out += hashlib.sha256(key + counter.to_bytes(8, "big")).digest()
        counter += 1
    return np.unpackbits(np.frombuffer(bytes(out), dtype=np.uint8))[:nbits]


def embed_xor_lsb(cover: np.ndarray, payload: bytes, key: bytes) -> np.ndarray:
    """LSB replacement XORed with a keystream (see module docstring). KEYED: extraction
    needs `key`, not just the stego image."""
    flat = cover.reshape(-1).copy()
    data = struct.pack(">I", len(payload)) + payload
    msg_bits = np.unpackbits(np.frombuffer(data, dtype=np.uint8))
    if msg_bits.size > flat.size:
        raise ValueError(f"payload ({len(payload)} B) does not fit in this cover "
                         f"(capacity {flat.size // 8 - 4} B)")
    ks = _keystream_bits(key, msg_bits.size)
    embed_bits = msg_bits ^ ks
    flat[:embed_bits.size] = (flat[:embed_bits.size] & 0xFE) | embed_bits
    return flat.reshape(cover.shape)


def extract_xor_lsb(stego: np.ndarray, key: bytes) -> bytes:
    flat = stego.reshape(-1)
    header_ks = _keystream_bits(key, HEADER_BITS)
    header_bits = (flat[:HEADER_BITS] & 1) ^ header_ks
    (length,) = struct.unpack(">I", np.packbits(header_bits).tobytes())
    end = HEADER_BITS + length * 8
    if end > flat.size:                                        # garbage/wrong-key header guard
        raise ValueError(f"decoded length ({length} B) exceeds this image's capacity "
                         f"({flat.size // 8} B) - wrong key, wrong method, or not a stego image")
    body_ks = _keystream_bits(key, end)[HEADER_BITS:end]
    body_bits = (flat[HEADER_BITS:end] & 1) ^ body_ks
    return np.packbits(body_bits).tobytes()


# ------------------------------------------------------------------ cipher payloads
def toy_rsa_textbook(message: bytes, n_bits: int) -> dict:
    """Textbook RSA (no padding), a toy modulus from TOY_KEY_TABLE. Returns the blob plus
    every value needed to independently verify a later attack (self-test style, like Q1/Q10).

    Toy moduli (15, 21, 35, 221) are far smaller than one ASCII byte (0-255), so every byte of
    `message` is reduced modulo N first (toy demos always use tiny messages for this reason -
    this just makes that automatic instead of making every caller remember it). A byte that
    reduces to 0 is bumped to 1 (RSA on 0 is a degenerate case, not a useful test).
    """
    spec = TOY_KEY_TABLE[n_bits]
    p, q, e = spec["p"], spec["q"], spec["e"]
    n = p * q
    d = pow(e, -1, (p - 1) * (q - 1))
    clamped = bytes((b % n) or 1 for b in message)
    blob = b"".join(pow(b, e, n).to_bytes((n.bit_length() + 7) // 8, "big") for b in clamped)
    return {"blob": blob, "cipher": "rsa_textbook", "n": n, "e": e, "d": d, "p": p, "q": q,
           "n_bits": n.bit_length(), "block_bytes": (n.bit_length() + 7) // 8,
           "plaintext_bytes_used": list(clamped)}


def large_toy_rsa_textbook(message: bytes, bits: int = LARGE_TOY_BITS) -> dict:
    """A bigger (non-Shor-reachable-here) RSA modulus, purely for testing the analyzer's
    ESTIMATE branch later. Built from two real random primes - still toy-labelled, but out of
    this project's Shor circuit's reach (src/quantum_break_stego.py caps at 16 bits)."""
    from sympy import randprime
    import random
    rng = random.Random(0)
    half = bits // 2
    p = randprime(2 ** (half - 1), 2 ** half)
    q = randprime(2 ** (half - 1), 2 ** half)
    n, e = p * q, 65537
    d = pow(e, -1, (p - 1) * (q - 1))
    if any(b >= n for b in message):
        raise ValueError("message byte too large for this modulus")
    blob = b"".join(pow(b, e, n).to_bytes((n.bit_length() + 7) // 8, "big") for b in message)
    return {"blob": blob, "cipher": "rsa_textbook", "n": n, "e": e, "d": d, "p": p, "q": q,
           "n_bits": n.bit_length(), "block_bytes": (n.bit_length() + 7) // 8,
           "note": "too large for the Shor stage here; analyzer should give an estimate"}


def rsa_oaep(message: bytes, bits: int = 1024) -> dict:
    """Real PKCS#1 OAEP, a real pycryptodome RSA key. One block only (OAEP has a max message
    size for a given key size); callers must keep `message` short enough."""
    from Crypto.PublicKey import RSA
    from Crypto.Cipher import PKCS1_OAEP
    key = RSA.generate(bits)
    cipher = PKCS1_OAEP.new(key.publickey())
    blob = cipher.encrypt(message)
    return {"blob": blob, "cipher": "rsa_oaep", "n_bits": bits,
           "private_key_pem": key.export_key().decode()}       # kept only for a round-trip check


def mlkem_hybrid(message: bytes) -> dict:
    """ML-KEM-768 + AES-256-GCM, via the project's own hybrid.py - never reimplemented here."""
    public_key, secret_key = hybrid.generate_keypair()
    blob = hybrid.hybrid_encrypt(public_key, message)
    return {"blob": blob, "cipher": "mlkem_hybrid", "overhead_bytes": hybrid.OVERHEAD,
           "public_key": public_key.hex(), "secret_key": secret_key.hex()}


# ------------------------------------------------------------------ the generator
def build_test_set(out_dir: Path, count: int, seed: int, toy_ns: list, oaep_bits: int,
                   cover_size: int, message: bytes):
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = []
    rng_seed = seed
    xor_key = b"test-set-xor-lsb-shared-key"            # fixed, documented key for this test set

    def next_seed():
        nonlocal rng_seed
        rng_seed += 1
        return rng_seed

    def save(name, stego_arr, record):
        path = out_dir / f"{name}.png"
        Image.fromarray(stego_arr).save(path)
        record["filename"] = path.name
        manifest.append(record)

    cipher_builders = {
        "rsa_textbook": [("rsa_textbook", lambda n=n: toy_rsa_textbook(message, n)) for n in toy_ns],
        # NOTE the n=n default-argument trick above: without it every lambda in this list would
        # capture `n` by reference and silently use toy_ns's LAST value for every entry (a
        # classic Python late-binding closure bug - caught by testing, not by inspection: two
        # different toy N values produced identically-labelled output until this was fixed).
        "rsa_textbook_large": [("rsa_textbook", lambda: large_toy_rsa_textbook(message))],
        "rsa_oaep": [("rsa_oaep", lambda: rsa_oaep(message, oaep_bits))],
        "mlkem_hybrid": [("mlkem_hybrid", lambda: mlkem_hybrid(message))],
    }

    for rep in range(count):
        # --- LSB and XOR-LSB, every cipher ---
        for group in ("rsa_textbook", "rsa_textbook_large", "rsa_oaep", "mlkem_hybrid"):
            for cipher_name, builder in cipher_builders[group]:
                payload = builder()
                blob = payload.pop("blob")
                cover = make_cover(cover_size, next_seed())
                try:
                    stego_lsb = embed_lsb(cover, blob)
                except ValueError as exc:
                    print(f"skip (too big for this cover): {cipher_name} {payload.get('n_bits')} "
                         f"bits - {exc}")
                    continue
                save(f"{cipher_name}_{payload.get('n_bits','')}_lsb_{rep}", stego_lsb,
                    {"method": "lsb", "message_bytes": len(message), **payload})

                cover2 = make_cover(cover_size, next_seed())
                try:
                    stego_xor = embed_xor_lsb(cover2, blob, xor_key)
                except ValueError as exc:
                    print(f"skip (too big for this cover, xor_lsb): {cipher_name} - {exc}")
                    continue
                save(f"{cipher_name}_{payload.get('n_bits','')}_xorlsb_{rep}", stego_xor,
                    {"method": "xor_lsb", "message_bytes": len(message),
                     "xor_key_hex": xor_key.hex(), **payload})

        # --- clean (negative) examples, no cipher at all ---
        clean = make_cover(cover_size, next_seed())
        save(f"clean_{rep}", clean, {"method": "clean", "cipher": "none"})

    manifest_path = out_dir / "manifest.json"
    manifest_path.write_text(json.dumps({
        "generated_by": "extras/generate_test_set.py", "count_per_case": count, "seed": seed,
        "toy_n_values": toy_ns, "oaep_bits": oaep_bits, "cover_size": cover_size,
        "message_used": message.decode(errors="replace"),
        "xor_lsb_note": "keyed hiding method defined by this script; see module docstring",
        "items": manifest}, indent=2) + "\n", encoding="utf-8")
    return manifest_path, len(manifest)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", default="outputs/test_set")
    ap.add_argument("--count", type=int, default=1, help="repeats per (method, cipher) case")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--toy-n", type=int, nargs="+", default=[15, 21, 35],
                    help="toy RSA moduli to include (from %s)" % sorted(TOY_KEY_TABLE))
    ap.add_argument("--oaep-bits", type=int, default=1024)
    ap.add_argument("--cover-size", type=int, default=256, help="cover image side in pixels")
    ap.add_argument("--message", default="HELLO", help="message bytes must each be < any toy N used")
    args = ap.parse_args()

    bad = [n for n in args.toy_n if n not in TOY_KEY_TABLE]
    if bad:
        ap.error(f"--toy-n values must be from {sorted(TOY_KEY_TABLE)}, got {bad}")

    out_dir = Path(args.out_dir)
    manifest_path, n_items = build_test_set(out_dir, args.count, args.seed, args.toy_n,
                                            args.oaep_bits, args.cover_size, args.message.encode())
    print(f"\nWrote {n_items} labelled images + manifest to {out_dir}")
    print(f"Manifest: {manifest_path}")
    print("\nREMINDER: these are generated files. Do not `git add` this folder; check "
         ".gitignore covers it (per the working rules, test images are never committed).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
