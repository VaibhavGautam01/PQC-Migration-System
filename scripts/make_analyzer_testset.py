"""
make_analyzer_testset.py - generate a labelled test set for the Stego Analyzer from our own project.

Images are made with the pinned image project's own embed_lsb (loaded by path, never edited), so they are
real images of our format. They are generated by this script and are never committed (outputs/tmp_* is ignored).

  python scripts/make_analyzer_testset.py
  python scripts/make_analyzer_testset.py --project data/targets/final-year-part1 --out outputs/tmp_analyzer_testset

Cases: toy textbook RSA for N = 15, 21, 35 (with the public key); the same N=15 image analysed without the
key; an ML-KEM-768 + AES-256-GCM image; a clean cover. Real-size RSA images are not generated: the pinned
project's message layout for a non-toy modulus is not known to this script (see docs/analyzer_spec.md).

labels.json lists, for every image, what the analyzer must say. scripts/analyzer_testset_run.py checks it.
"""
import argparse
import importlib.util
import json
import os
import sys
from math import gcd
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from stego_analyzer import toyformat  # noqa: E402

TOY_PRIMES = {15: (3, 5), 21: (3, 7), 35: (5, 7)}
COVER_SIZE = (300, 300)


def toy_public_key(n):
    p, q = TOY_PRIMES[n]
    phi = (p - 1) * (q - 1)
    return {"n": n, "e": next(x for x in range(3, phi) if gcd(x, phi) == 1)}


def load_embed(project_dir):
    file = Path(project_dir) / "lsb_stego.py"
    if not file.is_file():
        raise SystemExit(f"pinned image project not found at {file}: run git submodule update --init")
    spec = importlib.util.spec_from_file_location("pinned_lsb_stego_gen", file)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.embed_lsb


def make_cover(path, size=COVER_SIZE):
    from PIL import Image
    Image.frombytes("RGB", size, os.urandom(size[0] * size[1] * 3)).save(path)


def build_cases(message="HELLO"):
    """The cases, without any file: (name, hex payload or None, label dict)."""
    cases = []
    for n in TOY_PRIMES:
        key = toy_public_key(n)
        cases.append((f"toy_rsa_N{n}", toyformat.encrypt_blocks(message, key["e"], n),
                      {"expected_hiding": "lsb", "expected_cipher": "textbook_rsa", "expected_state": "broken_toy",
                       "public_key": key, "message": message}))
    key15 = toy_public_key(15)
    cases.append(("toy_rsa_N15_no_key", toyformat.encrypt_blocks(message, key15["e"], 15),
                  {"expected_hiding": "lsb", "expected_cipher": "unrecognised", "expected_state": "unrecognised",
                   "public_key": None, "message": message}))
    from pqc_stego import hybrid
    pk, _sk = hybrid.generate_keypair()
    cases.append(("ml_kem_aes_gcm", hybrid.hybrid_encrypt(pk, b"PQC!").hex(),
                  {"expected_hiding": "lsb", "expected_cipher": "ml_kem_aes_gcm", "expected_state": "resists",
                   "public_key": None, "message": None}))
    cases.append(("clean_image", None,
                  {"expected_hiding": "clean_or_unknown", "expected_cipher": None, "expected_state": "unrecognised",
                   "public_key": None, "message": None}))
    return cases


def generate(project_dir, out_dir, message="HELLO"):
    embed = load_embed(project_dir)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    labels = []
    for name, payload, label in build_cases(message):
        cover, stego = out / f"{name}_cover.png", out / f"{name}.png"
        make_cover(cover)
        if payload is None:
            cover.replace(stego)
        else:
            embed(str(cover), payload, str(stego))
            cover.unlink()
        labels.append({"file": stego.name, **label})
    (out / "labels.json").write_text(json.dumps(labels, indent=2), encoding="utf-8")
    return labels


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", default=str(ROOT / "data" / "targets" / "final-year-part1"))
    ap.add_argument("--out", default=str(ROOT / "outputs" / "tmp_analyzer_testset"))
    ap.add_argument("--message", default="HELLO")
    args = ap.parse_args(argv)
    labels = generate(args.project, args.out, args.message)
    print(f"Wrote {len(labels)} images and labels.json to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
