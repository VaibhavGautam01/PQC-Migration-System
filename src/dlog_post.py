"""
dlog_post.py - classical post-processing for Q10 (Shor's algorithm for the discrete log).

THE PROBLEM
-----------
Public: a prime p, a generator g of a subgroup of Z_p^*, and h = g^x mod p for a SECRET x.
Find x. (This underlies Diffie-Hellman and DSA: the scanner's DH/DSA detection feeds here.)

THE ALGORITHM, IN TWO STAGES (both stages are REAL quantum circuits)
----------------------------------------------------------------------
Stage 1, order finding: find r = the order of g mod p. This is EXACTLY Shor's order-finding
circuit (src/q1_shor_pe.py / shor_post.py), reused unchanged - the same circuit that factors
N=15, 21, 35 for Q1 finds the order of g in a prime group just as well. This is itself the
"change the question" test (rule 6) applied one more time: same code, a new kind of question.

Stage 2, the two-register circuit (q10_dlog.py): phase estimation on the function
    f(a, b) = g^a * h^(-b) mod p = g^(a - b*x) mod p,
which is periodic on the lattice generated by (r, 0) and (x, 1). The inverse QFT of a function
periodic on that lattice peaks on points (c1, c2) satisfying, for a random integer j (0 <= j < r):
    c1 = round(j * x * T / r) mod T        (register A, counts the "a" exponent of g)
    c2 = round(-j * T / r) mod T           (register B, counts the "b" exponent of h^-1)
where T = 2**t (t = counting qubits per register). VERIFIED NUMERICALLY against a known
instance (g=2, h=8, p=11, x=3, r=10): every peak with weight > 1e-4 matches this formula
exactly (the small-size residual peaks at low weight are phase-estimation imprecision, the
same effect Q1 sees with non-power-of-two orders).

CLASSICAL POST-PROCESSING OF ONE MEASUREMENT (y1, y2), GIVEN r (from stage 1)
------------------------------------------------------------------------------
    j = round(-y2 * r / T) mod r                      (from the c2 relation above)
    if gcd(j, r) != 1: this shot gives no information; try another shot
    x = (round(y1 * r / T) * modinv(j, r)) % r         (from the c1 relation, solved for x)
    VERIFY: g**x % p == h  (a check of the CANDIDATE, not a search for it - same pattern as
    Shor's factoring post-processing, rule 2)

Nothing here computes x without a measurement: r comes from a real circuit (stage 1), and
(y1, y2) comes from a real circuit (stage 2). This file only rounds and solves, as the
algorithm itself defines.
"""
from math import gcd


def check_inputs(g: int, h: int, p: int) -> None:
    """Raise ValueError unless p is at least 3 and g, h are in 1 < . < p."""
    if p < 3:
        raise ValueError("p must be at least 3")
    if not (1 < g < p and 1 < h < p):
        raise ValueError(f"need 1 < g, h < p (got g={g}, h={h}, p={p})")


def recover_j(y2: int, t: int, r: int) -> int:
    """Register B's measured value -> candidate j (0 <= j < r). Pure rounding: r is known
    exactly from stage 1, so this is simpler than Shor's continued fractions (which is needed
    only when the order/denominator is NOT already known)."""
    return round(-y2 * r / 2 ** t) % r


def recover_x_candidate(y1: int, y2: int, t: int, r: int, g: int, h: int, p: int):
    """One measurement (y1, y2) -> x, or None if this shot gives no information.

    Returns x only if it is VERIFIED: g**x mod p == h. Any x returned has therefore been
    checked against the public (g, h, p), not merely computed.
    """
    j = recover_j(y2, t, r)
    if j == 0 or gcd(j, r) != 1:
        return None
    j_inv = pow(j, -1, r)
    numerator = round(y1 * r / 2 ** t) % r
    x = (numerator * j_inv) % r
    return x if pow(g, x, p) == h else None


def analyse_counts(counts: dict, t: int, r: int, g: int, h: int, p: int) -> dict:
    """Post-process a whole measured histogram {"y1y2 bitstring": count} (2*t bits, register A
    first). Tries every distinct (y1, y2) outcome, most frequent first, and returns the first
    verified x. Everything here comes only from the measured counts and the known r (rule 2).
    """
    shots = sum(counts.values())
    by_pair = {}
    for bits, c in counts.items():
        y1, y2 = int(bits[:t], 2), int(bits[t:], 2)
        by_pair[(y1, y2)] = by_pair.get((y1, y2), 0) + c
    x_found, used_shots = None, 0
    tried = []
    for (y1, y2), c in sorted(by_pair.items(), key=lambda kv: -kv[1]):
        x = recover_x_candidate(y1, y2, t, r, g, h, p)
        tried.append({"y1": y1, "y2": y2, "count": c, "x_candidate": x})
        if x is not None and x_found is None:
            x_found, used_shots = x, c
        if x_found is not None and len(tried) >= 5:          # enough evidence, stop early
            break
    success_rate = used_shots / shots if (x_found is not None and shots) else 0.0
    return {"x": x_found, "attempts": tried, "success_rate": success_rate, "shots": shots}
